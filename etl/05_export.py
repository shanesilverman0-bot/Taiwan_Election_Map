"""Step 5: write the app JSON from data/canonical/*.csv.

  data/elections/{type}_{year}.json          county level, keyed by CONFIG.countyIdToCode letters
  data/elections/towns/{type}_{year}.json    town level, keyed by TOWNCODE
  data/entities/politicians.json             person registry (identity only, no party)

Old files' _meta.notes move to _meta.legacy_notes untouched (other old _meta text goes to _meta.legacy_meta).
The legacy meta is read from the existing output file if it is still the hand-entered version, else from the
previous export's legacy fields (idempotent).
    python3 -I etl/05_export.py
"""
import csv
import json
from decimal import Decimal, ROUND_HALF_UP
import os
import sys
from collections import defaultdict

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common

ELEC_DIR = os.path.join(common.REPO, "data", "elections")
SOURCE = ("Taiwan Central Election Commission (CEC) bulk election database, via kiang/db.cec.gov.tw "
          "(CC BY 4.0); generated by etl/05_export.py from data/canonical/*.csv")
ELECTION_LABEL = {"presidential": "Presidential", "magistrate": "County Magistrate / City Mayor (九合一)"}


def rd(name):
    return list(csv.DictReader(open(os.path.join(common.CANON, name), encoding="utf-8")))


def write_json(path, obj):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(obj, fh, ensure_ascii=False, indent=1)
        fh.write("\n")


def legacy_meta(path):
    """Return (legacy_notes, legacy_meta) from the file currently on disk."""
    if not os.path.exists(path):
        return None, None
    m = json.load(open(path, encoding="utf-8")).get("_meta", {})
    if "generated_by" in m:  # already regenerated: carry the stored legacy fields forward
        return m.get("legacy_notes"), m.get("legacy_meta")
    notes = m.get("notes")
    rest = {k: v for k, v in m.items() if k not in ("notes", "candidates")}
    # keep the old hand-entered candidate summary too, verbatim
    if "candidates" in m:
        rest["candidates"] = m["candidates"]
    return notes, rest


def en_name(rec):
    return rec["name_en"] or None


def main():
    elections = common.load_elections()
    geo_c = {c["COUNTYCODE"]: c for c in common.counties()}
    geo_t = {t["TOWNCODE"]: t for t in common.towns()}
    letters = common.config_county_letters()          # letter -> code
    code2letter = {v: k for k, v in letters.items()}
    people = {r["person_id"]: r for r in rd("people.csv")}
    contests = rd("contests.csv")
    candidacies = rd("candidacies.csv")
    results = rd("results_area.csv")
    turnout = rd("turnout.csv")

    cand_by_contest = defaultdict(list)
    for c in candidacies:
        cand_by_contest[c["contest_id"]].append(c)
    res_idx = defaultdict(dict)       # (contest, level, code) -> {pid: votes}
    for r in results:
        res_idx[(r["contest_id"], r["area_level"], r["area_code"])][r["person_id"]] = int(r["votes"])
    turn_idx = {(t["contest_id"], t["area_level"], t["area_code"]): t for t in turnout}

    def county_zh(code):
        return geo_c[code]["COUNTYNAME"].replace("台", "臺")

    def town_zh(code):
        return geo_t[code]["TOWNNAME"].replace("台", "臺")

    def cand_entry(c, votes, pct, full=True):
        p = people[c["person_id"]]
        e = {"politician_id": c["person_id"]}
        if full:
            e["name_zh"] = p["name_zh"]
            e["name_en"] = en_name(p)
        e["party"] = c["party_key"]
        if c["party_key"] == "OTHER":
            e["party_name_zh"] = c["party_name_zh"]
        if full:
            e["ballot_no"] = int(c["ballot_no"])
            e["incumbent"] = c["incumbent"] == "Y"
            e["elected"] = c["elected"] == "Y"
        e["votes"] = votes
        e["vote_pct"] = pct
        return e

    def area_entry(cands, contest_id, level, code, name_zh, name_en, extra=None, full=True):
        """cands: candidacies of the contest. Returns an area dict."""
        t = turn_idx[(contest_id, level, code)]
        v = res_idx[(contest_id, level, code)]
        valid = int(t["valid_votes"])
        entries = []
        for c in sorted(cands, key=lambda c: int(c["ballot_no"])):
            votes = v.get(c["person_id"], 0)
            pct = float((Decimal(votes) * 100 / Decimal(valid)).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)) if valid else 0.0
            entries.append(cand_entry(c, votes, pct, full))
        # winner = plurality in this area (single-seat race)
        top = max(entries, key=lambda e: e["votes"])
        d = {"name_zh": name_zh, "name_en": name_en}
        if extra:
            d.update(extra)
        d.update({"electorate": int(t["electorate"]), "turnout": float(t["turnout_pct"]),
                  "valid_votes": valid,
                  "winner": {"politician_id": top["politician_id"], "party": top["party"]},
                  "candidates": entries})
        return d

    used_people = set()
    for e in elections:
        eid, otype, year = e["id"], e["type"], e["year"]
        cs = [c for c in contests if c["election_id"] == eid]
        fname = f"{otype}_{year}.json"
        path = os.path.join(ELEC_DIR, fname)
        notes, lmeta = legacy_meta(path)
        meta = {"election": ELECTION_LABEL[otype], "year": year, "date": e["date"].isoformat()
                if hasattr(e["date"], "isoformat") else str(e["date"])}
        county_out, town_out = {}, {}
        if e["level"] == "national":
            c0 = cs[0]
            cid = c0["contest_id"]
            cl = cand_by_contest[cid]
            nat = turn_idx[(cid, "national", "00000")]
            meta["turnout"] = float(nat["turnout_pct"])
            meta["registered"] = int(nat["electorate"])
            meta["valid_votes"] = int(nat["valid_votes"])
            meta["candidates"] = []
            for c in sorted(cl, key=lambda c: int(c["ballot_no"])):
                p = people[c["person_id"]]
                rm = people.get(c["running_mate_person_id"])
                used_people.add(c["person_id"])
                if rm:
                    used_people.add(rm["person_id"])
                meta["candidates"].append({
                    "politician_id": c["person_id"], "name_zh": p["name_zh"], "name_en": en_name(p),
                    "party": c["party_key"], **({"party_name_zh": c["party_name_zh"]} if c["party_key"] == "OTHER" else {}),
                    "running_mate_zh": rm["name_zh"] if rm else None,
                    "running_mate_en": en_name(rm) if rm else None,
                    "running_mate_politician_id": rm["person_id"] if rm else None,
                    "ballot_no": int(c["ballot_no"]), "incumbent": c["incumbent"] == "Y",
                    "elected": c["elected"] == "Y",
                    "total_votes": int(c["votes"]), "total_pct": float(c["vote_pct"])})
            ccodes = sorted({r[1] for r in res_idx if r[0] == cid and r[1] == "county"} and
                            {r[2] for r in res_idx if r[0] == cid and r[1] == "county"})
            for code in ccodes:
                g = geo_c[code]
                county_out[g["COUNTYID"]] = area_entry(cl, cid, "county", code, county_zh(code), g["COUNTYENG"])
            tcodes = sorted({r[2] for r in res_idx if r[0] == cid and r[1] == "town"})
            for code in tcodes:
                g = geo_t[code]
                town_out[code] = area_entry(cl, cid, "town", code, town_zh(code), g["TOWNENG"],
                                            extra={"county_id": g["COUNTYID"]}, full=False)
            used_people |= {c["person_id"] for c in cl}
        else:
            reg_total = vt_total = 0
            for c0 in sorted(cs, key=lambda c: c["area_code"]):
                cid, code = c0["contest_id"], c0["area_code"]
                cl = cand_by_contest[cid]
                g = geo_c[code]
                entry = area_entry(cl, cid, "county", code, county_zh(code), g["COUNTYENG"])
                if code in ("10020",) and c0["date"] != e["date"].isoformat():
                    entry["date"] = c0["date"]       # Chiayi City 2022 rerun
                    meta["date_chiayi_city"] = c0["date"]
                # sanity: CEC elected flag agrees with plurality
                el = [c for c in cl if c["elected"] == "Y"]
                assert len(el) == 1 and el[0]["person_id"] == entry["winner"]["politician_id"], cid
                county_out[g["COUNTYID"]] = entry
                t = turn_idx[(cid, "county", code)]
                reg_total += int(t["electorate"]); vt_total += int(t["total_votes"])
                used_people |= {c["person_id"] for c in cl}
                for tcode in sorted({r[2] for r in res_idx if r[0] == cid and r[1] == "town"}):
                    gt = geo_t[tcode]
                    town_out[tcode] = area_entry(cl, cid, "town", tcode, town_zh(tcode), gt["TOWNENG"],
                                                 extra={"county_id": gt["COUNTYID"]}, full=False)
            meta["registered"] = reg_total
            meta["turnout_national"] = float((Decimal(vt_total) * 100 / Decimal(reg_total)).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP))
            meta["races"] = len(cs)
        meta["source"] = SOURCE
        meta["generated_by"] = "etl/05_export.py"
        meta["legacy_notes"] = notes
        meta["legacy_meta"] = lmeta

        # not-contested entries for every county on the boundary file
        for code, g in geo_c.items():
            if g["COUNTYID"] not in county_out:
                county_out[g["COUNTYID"]] = {"name_zh": county_zh(code), "name_en": g["COUNTYENG"],
                                             "not_contested": True, "candidates": []}
        out = {"_meta": meta}
        for k in sorted(county_out):
            out[k] = county_out[k]
        write_json(path, out)

        tmeta = {"election": meta["election"], "year": year, "date": meta["date"], "level": "town",
                 "source": SOURCE, "generated_by": "etl/05_export.py",
                 "note": ("Keys are TOWNCODE from data/geo/towns-10t.json. Pre-2010 towns are mapped to the "
                          "current district codes by name (see reports/phase-1/town_crosswalk.csv)."),
                 "candidates_registry": "data/entities/politicians.json"}
        tout = {"_meta": tmeta}
        for k in sorted(town_out):
            tout[k] = town_out[k]
        write_json(os.path.join(ELEC_DIR, "towns", fname), tout)
        print(f"{fname}: {sum(1 for k,v in county_out.items() if not v.get('not_contested'))} counties, "
              f"{len(town_out)} towns")

    # ---- registry: identity only, no party
    reg = {"_meta": {"notes": ("Person registry generated by etl/05_export.py from data/canonical/people.csv. "
                               "Keys are person_id = sha1(name_zh|birth_date)[:8]. Identity only: party lives on each "
                               "candidate entry in the election files. name_en is null unless sourced."),
                     "generated_by": "etl/05_export.py"}}
    for pid in sorted(used_people):
        p = people[pid]
        reg[pid] = {"name_zh": p["name_zh"], "name_en": en_name(p),
                    "birth_year": int(p["birth_date"][:4]) if p["birth_date"] else None,
                    "wikidata_qid": p["wikidata_qid"] or None,
                    "wiki_url": p["wiki_url"] or None, "photo": p["photo_url"] or None}
    write_json(os.path.join(common.REPO, "data/entities/politicians.json"), reg)
    print("registry:", len(reg) - 1, "people")


if __name__ == "__main__":
    main()
